        'maxGridExportPeak_kW', ...
        'maxBessChargePeak_kW', ...
        'maxBessDischargePeak_kW' ...
    }, ...
    'source', { ...
        'P_load_kW', ...
        'P_pv_available_kW', ...
        'P_pv_to_load_kW', ...
        'P_pv_to_bess_kW', ...
        'P_bess_to_load_kW', ...
        'P_grid_import_kW', ...
        'P_grid_export_kW', ...
        'P_curtailment_kW', ...
        'P_inv_loss_kW', ...
        'P_internal_network_loss_kW', ...
        'P_load_kW', ...
        'P_pv_available_kW', ...
        'P_grid_import_kW', ...
        'P_grid_export_kW', ...
        'P_pv_to_bess_kW', ...
        'P_bess_to_load_kW' ...
    }, ...
    'mode', { ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'max', ...
        'max', ...
        'max', ...
        'max', ...
        'max', ...
        'max' ...
    });

    extraScalarLossMetrics = struct( ...
    'name', { ...
        'bessCellLoss_kWh', ...
        'bessSocFullLoss_kWh', ...
        'bessSocEmptyLoss_kWh', ...
        'bessTotalInternalLoss_kWh', ...
        'dcdcConversionLoss_kWh', ...
        'dcdcPowerClipped_kWh', ...
        'inverterConversionLoss_kWh', ...
        'inverterPowerClipped_kWh', ...
        'inverterPvConversionLoss_kWh', ...
        'inverterBessConversionLoss_kWh', ...
        'inverterPvClipped_kWh', ...
        'inverterBessClipped_kWh' ...
    }, ...
    'source', { ...
        'P_bess_cell_loss_kW', ...
        'P_bess_soc_full_loss_kW', ...
        'P_bess_soc_empty_loss_kW', ...
        'P_bess_total_internal_loss_kW', ...
        'P_dcdc_conversion_loss_kW', ...
        'P_dcdc_power_clipped_kW', ...
        'P_inv_conversion_loss_kW', ...
        'P_inv_power_clipped_kW', ...
        'P_inv_pv_conversion_loss_kW', ...
        'P_inv_bess_conversion_loss_kW', ...
        'P_inv_pv_clipped_kW', ...
        'P_inv_bess_clipped_kW' ...
    }, ...
    'mode', { ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum', ...
        'energySum' ...
    });

    cfg.output.scalarMetrics = [cfg.output.scalarMetrics, extraScalarLossMetrics];

    % ---------------------------------------------------------------------
    % OUTPUT METRICS - PROFILE
    % ---------------------------------------------------------------------
    cfg.output.profileMetrics = struct( ...
    'name', { ...
        'meanLoad_kW', ...
        'peakLoad_kW', ...
        'meanPvAvailable_kW', ...
        'peakPvAvailable_kW', ...
        'meanPvToLoad_kW', ...
        'peakPvToLoad_kW', ...
        'meanPvToBess_kW', ...
        'peakPvToBess_kW', ...
        'meanBessToLoad_kW', ...
        'peakBessToLoad_kW', ...
        'meanGridImport_kW', ...
        'peakGridImport_kW', ...
        'meanGridExport_kW', ...
        'peakGridExport_kW', ...
        'meanCurtailmentPower_kW', ...
        'peakCurtailmentPower_kW', ...
        'meanSoC', ...
        'minSoC', ...
        'maxSoC', ...
        'meanInverterLoss_kW', ...
        'peakInverterLoss_kW', ...
        'meanInternalNetworkLoss_kW', ...
        'peakInternalNetworkLoss_kW' ...
    }, ...
    'source', { ...
        'P_load_kW', ...
        'P_load_kW', ...
        'P_pv_available_kW', ...
        'P_pv_available_kW', ...
        'P_pv_to_load_kW', ...
        'P_pv_to_load_kW', ...
        'P_pv_to_bess_kW', ...
        'P_pv_to_bess_kW', ...
        'P_bess_to_load_kW', ...
        'P_bess_to_load_kW', ...
        'P_grid_import_kW', ...
        'P_grid_import_kW', ...
        'P_grid_export_kW', ...
        'P_grid_export_kW', ...
        'P_curtailment_kW', ...
        'P_curtailment_kW', ...
        'SoC', ...
        'SoC', ...
        'SoC', ...
        'P_inv_loss_kW', ...
        'P_inv_loss_kW', ...
        'P_internal_network_loss_kW', ...
        'P_internal_network_loss_kW' ...
    }, ...
    'mode', { ...
