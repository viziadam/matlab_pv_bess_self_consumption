    cfg.cost.bess_huf_per_kWh = 120000;
    cfg.cost.bess_power_huf_per_kW = 30000;
    cfg.cost.inverter_huf_per_kW = 50000;

    % Grid-connected self-consumption gazdasagi parameterek.
    cfg.cost.grid_import_huf_per_kWh = 75;
    cfg.cost.grid_export_huf_per_kWh = 0;

    % ---------------------------------------------------------------------
    % Simulation / storage
    % ---------------------------------------------------------------------
    cfg.sim.saveAfterEachCandidate = true;
    cfg.sim.verbose = true;

    % Ha true, akkor a metrikafrissites hibat dob, ha egy dayVectors source
    % mezo hianyzik.
    cfg.sim.strictMetricSources = true;

    % ---------------------------------------------------------------------
    % OUTPUT METRICS - SCALAR
    % ---------------------------------------------------------------------
    % A napi szimulacios fuggvenynek ezeket a dayVectors mezoket kell
    % eloallitani.
    %
    % Grid-connected self-consumption dayVectors ajanlott mezok:
    %
    %   P_load_kW
    %   P_pv_available_kW
    %   P_pv_to_load_kW
    %   P_pv_to_bess_kW
    %   P_bess_to_load_kW
    %   P_grid_import_kW
    %   P_grid_export_kW
    %   P_curtailment_kW
    %   P_inv_loss_kW
    %   P_internal_network_loss_kW
    %
    % Vesztesegmezok:
    %   P_bess_cell_loss_kW
    %   P_bess_soc_full_loss_kW
    %   P_bess_soc_empty_loss_kW
    %   P_bess_total_internal_loss_kW
    %   P_dcdc_conversion_loss_kW
    %   P_dcdc_power_clipped_kW
    %   P_inv_conversion_loss_kW
    %   P_inv_power_clipped_kW
    %   P_inv_pv_conversion_loss_kW
    %   P_inv_bess_conversion_loss_kW
    %   P_inv_pv_clipped_kW
    %   P_inv_bess_clipped_kW
    % ---------------------------------------------------------------------

